// new-account: a brand-new TEST account. The phrase is generated on this laptop, the account is
// registered with IdGateway.register on OP Mainnet, then it logs in exactly like `login`.
// This is the one command in threecast that spends money, and it asks before it does.

import { ID_GATEWAY_ADDRESS, ID_REGISTRY_ADDRESS, STORAGE_REGISTRY_ADDRESS, idGatewayABI, idRegistryABI, storageRegistryABI } from "@farcaster/core";
import { BaseError, createPublicClient, createWalletClient, formatEther, getAddress, http, isAddress, parseEventLogs, zeroAddress } from "viem";
import type { Address, HDAccount } from "viem";
import { english, generateMnemonic, mnemonicToAccount } from "viem/accounts";
import { optimism } from "viem/chains";
import { authorize, readPhrase, requireSynced } from "./account.ts";
import { TcError } from "./errors.ts";
import { short } from "./format.ts";
import type { Hub } from "./hub.ts";
import { confirm, hint, ok, say, step, warn } from "./out.ts";
import { savePhrase } from "./store.ts";
import type { Account } from "./store.ts";

export const OP_RPC = "https://mainnet.optimism.io";

// What to ask for on top of the price. register() is one IdRegistry write plus one storage rent;
// 300k gas is a ceiling, and OP's L1 data fee for a call this small is far below the allowance.
// Unused gas is never charged; whatever is left stays in the account's address.
const REGISTER_GAS = 300_000n;
const L1_FEE_ALLOWANCE = 2_000_000_000_000n; // 0.000002 ETH
const MICRO_ETH = 1_000_000_000_000n;

export interface NewAccountOptions {
  /** An address that can recover the account if the phrase is lost. Default: none. */
  recovery?: string;
  /** Resume with a phrase generated by an earlier run instead of making a new one. */
  phraseFile?: string;
  rpcUrl?: string;
  /** Asks the user; tests answer instead. */
  confirm?: (question: string) => Promise<boolean>;
  pollMs?: number;
}

export async function newAccount(hub: Hub, options: NewAccountOptions = {}): Promise<Account> {
  const ask = options.confirm ?? confirm;
  warn("new-account registers a brand-new Farcaster account on OP Mainnet, which costs real ETH: about $0.20 for the account and its first storage unit, plus a little gas. Use it for a TEST account.");
  // Checked first: there is no point paying for an account the node cannot log in yet.
  await requireSynced(hub);
  const recovery = recoveryAddress(options.recovery);
  const phrase = options.phraseFile ? await readPhrase(options.phraseFile) : await newPhrase(ask);
  const custody = mnemonicToAccount(phrase);
  const op = opClient(options.rpcUrl ?? OP_RPC, options.pollMs ?? 4_000);

  step(`Checking whether ${short(custody.address)} already has an FID (IdRegistry.idOf on OP Mainnet)…`);
  const existing = await rpc(() => op.readContract({ address: ID_REGISTRY_ADDRESS, abi: idRegistryABI, functionName: "idOf", args: [custody.address] }));
  if (existing === 0n) await register(op, custody, recovery, ask, options);
  else ok(`It is already FID ${existing}, so there is nothing to pay. On to the app key.`);

  return authorize(hub, phrase, { waitForFid: true });
}

function opClient(url: string, pollMs: number) {
  return createPublicClient({ chain: optimism, transport: http(url), pollingInterval: pollMs });
}

type OpClient = ReturnType<typeof opClient>;

function recoveryAddress(raw: string | undefined): Address {
  if (raw === undefined) {
    hint("No recovery address: if the phrase is lost, so is the account. Fine for a test; --recovery 0x… sets one.");
    return zeroAddress;
  }
  if (!isAddress(raw, { strict: false })) throw new TcError(`"${raw}" is not an Ethereum address.`, "--recovery takes a 0x address you control.");
  return getAddress(raw);
}

async function newPhrase(ask: (question: string) => Promise<boolean>): Promise<string> {
  step("Generating a new 12-word recovery phrase on this laptop (BIP-39, 128 bits from the operating system's random source)…");
  const phrase = generateMnemonic(english);
  const words = phrase.split(" ");
  say();
  say("  The new account's recovery phrase. It is shown this once: write it down now.");
  say();
  for (let row = 0; row < 3; row++) {
    say(`    ${words.slice(row * 4, row * 4 + 4).map((w, i) => `${String(row * 4 + i + 1).padStart(2)} ${w.padEnd(10)}`).join(" ")}`);
  }
  say();
  hint("Whoever has these words owns the account. You need them to log in anywhere else.");
  const address = mnemonicToAccount(phrase).address;
  const save = await ask("Also save the phrase in ~/.threecast/accounts/ (a file only you can read)?").catch((e: unknown) => {
    if (e instanceof TcError) throw new TcError("Cancelled. Nothing was saved or paid.", "./threecast new-account starts over, with a new phrase.");
    throw e;
  });
  if (save) {
    const path = savePhrase(address, phrase);
    ok(`Saved to ${path}. If you stop before paying, resume with: ./threecast new-account --phrase-file ${path}`);
  } else {
    hint("Not saved. If you stop before paying, put the 12 words in a file and resume with --phrase-file FILE.");
  }
  return phrase;
}

async function register(op: OpClient, custody: HDAccount, recovery: Address, ask: (question: string) => Promise<boolean>, options: NewAccountOptions): Promise<void> {
  const readPrice = () => rpc(() => op.readContract({ address: ID_GATEWAY_ADDRESS, abi: idGatewayABI, functionName: "price" }));
  step("Reading the price of an account with one storage unit (IdGateway.price() on OP Mainnet)…");
  const [price, ethUsd, gasPrice] = await Promise.all([
    readPrice(),
    rpc(() => op.readContract({ address: STORAGE_REGISTRY_ADDRESS, abi: storageRegistryABI, functionName: "ethUsdPrice" })),
    rpc(() => op.getGasPrice()),
  ]);
  const gas = gasPrice * REGISTER_GAS + L1_FEE_ALLOWANCE;
  // Rounded up to a millionth of an ETH, an amount people can type into a wallet.
  const needed = ((price + gas + MICRO_ETH - 1n) / MICRO_ETH) * MICRO_ETH;
  ok(`An account costs ${formatEther(price)} ETH (about ${usd(price, ethUsd)}); gas adds at most ${formatEther(gas)} ETH.`);
  say();
  say(`  Send at least ${formatEther(needed)} ETH (about ${usd(needed, ethUsd)}) on OP Mainnet (Optimism, chain id 10) to the account's address:`);
  say();
  say(`    ${custody.address}`);
  say();
  hint("It has to arrive on Optimism. ETH sent on Ethereum mainnet or Base lands somewhere this cannot see.");

  step("Waiting for it to arrive (checking the balance every 10 s; Ctrl-C stops, nothing has been spent)…");
  let balance = await rpc(() => op.getBalance({ address: custody.address }));
  while (balance < needed) {
    await new Promise((r) => setTimeout(r, options.pollMs ?? 10_000));
    balance = await rpc(() => op.getBalance({ address: custody.address }));
  }
  ok(`Received: the address holds ${formatEther(balance)} ETH.`);

  // The price follows the ETH/USD rate, so it is read again right before paying.
  const value = await readPrice();
  if (value + gas > balance) {
    throw new TcError(`The price rose to ${formatEther(value)} ETH while waiting.`, `Send a little more to ${custody.address}, then resume with --phrase-file.`);
  }
  const recoveryLabel = recovery === zeroAddress ? "no recovery address" : `recovery ${recovery}`;
  // Ctrl-C at this question counts as no.
  const pay = await ask(`Pay ${formatEther(value)} ETH from ${short(custody.address)} to IdGateway.register (${recoveryLabel}) on OP Mainnet now?`).catch((e: unknown) => {
    if (e instanceof TcError) return false;
    throw e;
  });
  if (!pay) {
    throw new TcError(`Stopped before paying. The ETH stays at ${custody.address}.`, "Resume any time with ./threecast new-account --phrase-file FILE (the 12 words in FILE).");
  }

  step("Checking the call with a dry run (eth_call), then signing it on this laptop and sending it…");
  const { request } = await rpc(() =>
    op.simulateContract({ account: custody, address: ID_GATEWAY_ADDRESS, abi: idGatewayABI, functionName: "register", args: [recovery], value }),
  );
  const wallet = createWalletClient({ account: custody, chain: optimism, transport: http(options.rpcUrl ?? OP_RPC) });
  const hash = await rpc(() => wallet.writeContract(request));
  ok(`Sent ${hash}`);
  hint(`https://optimistic.etherscan.io/tx/${hash}`);

  step("Waiting for it to be included in a block…");
  const receipt = await op.waitForTransactionReceipt({ hash, timeout: 300_000 }).catch(() => {
    throw new TcError(
      "The transaction was sent, but no receipt arrived within 5 minutes.",
      `Check https://optimistic.etherscan.io/tx/${hash}. Once it is in, resume with --phrase-file: a registered address is not charged again.`,
    );
  });
  if (receipt.status !== "success") {
    throw new TcError("The registration transaction failed onchain.", `Details: https://optimistic.etherscan.io/tx/${hash}`);
  }
  const [event] = parseEventLogs({ abi: idRegistryABI, eventName: "Register", logs: receipt.logs });
  ok(`Registered FID ${event?.args.id ?? "?"} with one storage unit.`);
}

// StorageRegistry.ethUsdPrice has 8 decimals, like the Chainlink feed it caches.
function usd(wei: bigint, ethUsd: bigint): string {
  const cents = (wei * ethUsd) / 10n ** 24n;
  return `$${(Number(cents) / 100).toFixed(2)}`;
}

async function rpc<T>(call: () => Promise<T>): Promise<T> {
  try {
    return await call();
  } catch (e) {
    if (e instanceof TcError) throw e;
    const why = e instanceof BaseError ? e.shortMessage : e instanceof Error ? e.message : String(e);
    throw new TcError(`OP Mainnet did not go through: ${why}`, "Try again in a minute, or pass --rpc URL to use another Optimism RPC endpoint.");
  }
}
